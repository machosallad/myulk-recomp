"""Embed font files into a C++ source file.

Usage: python embed_fonts.py OUT.cpp NAME=PATH [NAME=PATH ...]

Writes win16::fontdata::kFonts (name, bytes, size) so the program carries its
fonts on every platform without loading files at run time.
"""
import os
import sys


def main() -> int:
    out = sys.argv[1]
    entries = [a.split("=", 1) for a in sys.argv[2:]]
    lines = ["// Generated by tools/embed_fonts.py. Do not edit.", "#include <cstddef>", "",
             "namespace win16::fontdata {", ""]
    for i, (name, path) in enumerate(entries):
        data = open(path, "rb").read()
        lines.append(f"// {name}: {os.path.basename(path)}, {len(data)} bytes")
        lines.append(f"alignas(4) static const unsigned char kData{i}[] = {{")
        for p in range(0, len(data), 32):
            lines.append("    " + ",".join(str(b) for b in data[p:p + 32]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("struct Font { const char* name; const unsigned char* data; std::size_t size; };")
    lines.append("extern const Font kFonts[] = {")
    for i, (name, _path) in enumerate(entries):
        lines.append(f'    {{"{name}", kData{i}, sizeof kData{i}}},')
    lines.append("};")
    lines.append(f"extern const int kFontCount = {len(entries)};")
    lines.append("}  // namespace win16::fontdata")
    text = "\n".join(lines) + "\n"
    if not os.path.exists(out) or open(out, encoding="utf-8").read() != text:
        with open(out, "w", encoding="utf-8") as fh:
            fh.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
